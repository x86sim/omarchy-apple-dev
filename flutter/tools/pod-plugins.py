#!/usr/bin/env python3
"""Build the Flutter plugins that only have a podspec, with CocoaPods and tools/xcbuild.py, for build.sh.

  pod-plugins.py <flutter app dir> <shell package dir> <dir with Flutter.framework>

Reads <shell package>/pods.json (gen-shell-package.py lists the CocoaPods-only plugins there). In
<shell package>/pods it writes a Podfile with those plugins (and a local Flutter pod vendoring the engine
framework build.sh uses), runs `pod install` (cocoapods/install.sh's pod, without integrating into the app's
project), and builds the Pods-Runner target for iphoneos in Release with xcbuild. Prints one JSON object:
  swift_args  arguments for `swift build` that link the plugins (-Xlinker -L/-l/-framework) into Runner
  embed       dynamic frameworks the app must carry in Frameworks/ (vendored by a pod, Flutter excluded)
  bundles     resource bundles the pods made, for the app's root
Nothing to do (no such plugins): {"swift_args": [], "embed": [], "bundles": []}.
"""
import json
import os
import shlex
import shutil
import subprocess
import sys

here = os.path.dirname(os.path.abspath(__file__))
fork = os.path.dirname(os.path.dirname(here))
app, shell, fwdir = (os.path.abspath(a) for a in sys.argv[1:4])
spec = json.load(open(os.path.join(shell, "pods.json")))
empty = {"swift_args": [], "embed": [], "bundles": []}
if not spec["plugins"]:
    print(json.dumps(empty))
    sys.exit(0)


def log(msg):
    sys.stderr.write(msg + "\n")


pods = os.path.join(shell, "pods")
os.makedirs(os.path.join(pods, "Flutter"), exist_ok=True)
fw = os.path.join(pods, "Flutter", "Flutter.framework")
if os.path.lexists(fw):
    os.remove(fw) if os.path.islink(fw) else shutil.rmtree(fw)
os.symlink(os.path.join(fwdir, "Flutter.framework"), fw)
open(os.path.join(pods, "Flutter", "Flutter.podspec"), "w").write("""# Generated by flutter/tools/pod-plugins.py: the engine framework build.sh links, for the plugins' `dependency 'Flutter'`
Pod::Spec.new do |s|
  s.name = 'Flutter'
  s.version = '1.0.0'
  s.summary = 'Flutter engine'
  s.homepage = 'https://flutter.dev'
  s.license = { :type => 'BSD' }
  s.author = { 'Flutter Dev Team' => 'flutter-dev@googlegroups.com' }
  s.source = { :git => 'https://github.com/flutter/engine.git' }
  s.ios.deployment_target = '13.0'
  s.vendored_frameworks = 'Flutter.framework'
end
""")
min_ios = spec.get("min_ios") or "13.0"
lines = [f"platform :ios, '{min_ios}'",
         "install! 'cocoapods', :integrate_targets => false, :warn_for_unused_master_specs_repo => false",
         f"project '{os.path.join(app, 'ios', 'Runner.xcodeproj')}'",
         "target 'Runner' do",
         "  pod 'Flutter', :path => 'Flutter'"]
for p in spec["plugins"]:
    lines.append(f"  pod '{p['name']}', :path => '{p['path']}'")
lines += ["end",
          "post_install do |installer|",
          "  installer.pods_project.targets.each do |t|",
          "    t.build_configurations.each { |c| c.build_settings['IPHONEOS_DEPLOYMENT_TARGET'] = '" + min_ios + "' }",
          "  end",
          "end", ""]
podfile = "\n".join(lines)
pf = os.path.join(pods, "Podfile")
if not (os.path.exists(pf) and open(pf).read() == podfile):
    open(pf, "w").write(podfile)
pod = shutil.which("pod") or os.path.expanduser("~/.local/share/omarchy-apple-dev/cocoapods/bin/pod")
if not os.path.exists(pod):
    sys.exit("CocoaPods-only plugins need CocoaPods: ./install-toolchain.sh --cocoapods")
lock, manifest = os.path.join(pods, "Podfile.lock"), os.path.join(pods, "Pods/Manifest.lock")
if not (os.path.exists(manifest) and os.path.exists(lock) and open(lock).read() == open(manifest).read()
        and os.path.getmtime(pf) <= os.path.getmtime(manifest)):
    log("== pod install (" + ", ".join(p["name"] for p in spec["plugins"]) + ")")
    r = subprocess.run([pod, "install"], cwd=pods, stdout=sys.stderr)
    if r.returncode:
        sys.exit("pod install failed")
xcbuild = [sys.executable, os.path.join(fork, "tools/xcbuild.py"), "-project", os.path.join(pods, "Pods/Pods.xcodeproj"),
           "-target", "Pods-Runner", "-sdk", "iphoneos", "-configuration", "Release",
           "-derivedDataPath", os.path.join(pods, "build/xcbuild")]
log("== xcbuild Pods-Runner")
r = subprocess.run(xcbuild, cwd=pods, stdout=sys.stderr)
if r.returncode:
    sys.exit("building the CocoaPods plugins failed")
show = subprocess.run(xcbuild + ["-showBuildSettings"], cwd=pods, capture_output=True, text=True).stdout
st = {}
for line in show.splitlines():
    k, sep, v = line.strip().partition(" = ")
    if sep:
        st[k] = v
products = st.get("PODS_CONFIGURATION_BUILD_DIR") or os.path.join(pods, "build/xcbuild/Build/Products/Release-iphoneos")
args = []


def split(v):
    try:
        return shlex.split(v)
    except ValueError:
        return v.split()


for d in split(st.get("LIBRARY_SEARCH_PATHS", "")):
    if os.path.isabs(d) and os.path.isdir(d):
        args += ["-Xlinker", "-L", "-Xlinker", d]
for d in split(st.get("FRAMEWORK_SEARCH_PATHS", "")) + [os.path.join(products, "XCFrameworkIntermediates")]:
    if os.path.isabs(d) and os.path.isdir(d):
        args += ["-Xlinker", "-F", "-Xlinker", d]
# the aggregate target clears OTHER_LDFLAGS for itself; the app's flags are in its xcconfig
xcc = os.path.join(pods, "Pods/Target Support Files/Pods-Runner/Pods-Runner.release.xcconfig")
ld = []
for line in open(xcc) if os.path.exists(xcc) else []:
    k, sep, v = line.partition("=")
    if sep and k.strip() == "OTHER_LDFLAGS":
        ld = split(v.replace("$(inherited)", ""))
i = 0
while i < len(ld):
    x = ld[i]
    if x == "-framework" and i + 1 < len(ld):
        if ld[i + 1] != "Flutter":  # build.sh links Flutter itself
            args += ["-Xlinker", "-framework", "-Xlinker", ld[i + 1]]
        i += 2
        continue
    if x.startswith("-l") or x == "-ObjC":
        args += ["-Xlinker", x]
    elif x in ("-weak_framework",) and i + 1 < len(ld):
        args += ["-Xlinker", x, "-Xlinker", ld[i + 1]]
        i += 1
    i += 1
embed, bundles = [], []
xci = os.path.join(products, "XCFrameworkIntermediates")
for root, dirs, _ in os.walk(xci):
    for d in list(dirs):
        if d.endswith(".framework"):
            dirs.remove(d)
            p = os.path.join(root, d)
            exe = os.path.join(p, d[:-10])
            if d != "Flutter.framework" and os.path.exists(exe):
                with open(exe, "rb") as f:
                    if f.read(4) in (b"\xcf\xfa\xed\xfe",):  # a Mach-O image, not an ar archive
                        embed.append(p)
for d in sorted(os.listdir(products)) if os.path.isdir(products) else []:
    sub = os.path.join(products, d)
    for b in os.listdir(sub) if os.path.isdir(sub) else []:
        if b.endswith(".bundle"):
            bundles.append(os.path.join(sub, b))
print(json.dumps({"swift_args": args, "embed": embed, "bundles": bundles}))
