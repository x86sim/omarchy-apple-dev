#!/usr/bin/env python3
"""tuist on Linux: `tuist generate` for Tuist projects (Project.swift, Workspace.swift, Tuist/ProjectDescriptionHelpers),
where Tuist itself runs on macOS only.

The manifests are evaluated as Tuist evaluates them: compiled against Tuist's own ProjectDescription library (built on
Linux by tuist/install.sh from the pinned Tuist release) and run with --tuist-dump, which prints the project as Tuist's
JSON. That project is then written as an XcodeGen spec (Derived/x86sim/<Name>.xcodegen.json) and generated by
XcodeGen (xcodegen/install.sh) into <Name>.xcodeproj, with <Name>.xcworkspace around it as Tuist makes it.

    tuist generate [--path DIR] [--no-open]    the Xcode project and workspace
    tuist install                               nothing to do (Swift Build resolves Swift packages when it builds)
    tuist dump [project|workspace] [--path DIR] the manifest as Tuist's JSON
    tuist version

What is covered: targets (products, destinations, deployment targets, Info.plist files and Tuist's default / extended
Info.plists, entitlements, source / resource globs with excludes, localized resources, settings and configurations,
pre / post scripts), dependencies on targets, Swift packages (Project packages and Tuist/Package.swift's), frameworks,
xcframeworks, libraries and SDKs, explicit and automatic schemes, ProjectDescriptionHelpers. Not covered: plugins,
several projects in one workspace, Tuist's caching / selective testing (server features), resource synthesizers.
"""
import glob
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.realpath(__file__))
FORK = os.path.dirname(HERE)
OPAQUE = (".xcassets", ".icon", ".bundle", ".xcdatamodeld", ".xcmappingmodel", ".scnassets", ".rcproject",
          ".playground", ".framework", ".xcframework", ".docc", ".mlpackage", ".xcstrings", ".storyboardc")
PRODUCT_TYPES = {"app": "application", "framework": "framework", "staticFramework": "framework.static",
                 "staticLibrary": "library.static", "dynamicLibrary": "library.dynamic", "unitTests": "bundle.unit-test",
                 "unit_tests": "bundle.unit-test", "uiTests": "bundle.ui-testing", "ui_tests": "bundle.ui-testing",
                 "bundle": "bundle", "appExtension": "app-extension", "app_extension": "app-extension",
                 "watch2App": "application.watchapp2", "watch2Extension": "watchkit2-extension",
                 "appClip": "application.on-demand-install-capable", "commandLineTool": "tool",
                 "messagesExtension": "app-extension.messages", "stickerPackExtension": "app-extension.messages-sticker-pack",
                 "extensionKitExtension": "extensionkit-extension", "tvTopShelfExtension": "tv-app-extension",
                 "xpc": "xpc-service", "systemExtension": "system-extension", "macro": "tool"}
CAMEL = {"unit_tests": "unitTests", "ui_tests": "uiTests", "app_extension": "appExtension",
         "static_library": "staticLibrary", "dynamic_library": "dynamicLibrary", "static_framework": "staticFramework",
         "watch2_app": "watch2App", "watch2_extension": "watch2Extension", "app_clip": "appClip",
         "command_line_tool": "commandLineTool", "messages_extension": "messagesExtension",
         "sticker_pack_extension": "stickerPackExtension", "extension_kit_extension": "extensionKitExtension",
         "tv_top_shelf_extension": "tvTopShelfExtension", "system_extension": "systemExtension"}
PLATFORM_OF = {"iPhone": "iOS", "iPad": "iOS", "macWithiPadDesign": "iOS", "macCatalyst": "iOS", "appleWatch": "watchOS",
               "appleTv": "tvOS", "appleVision": "visionOS", "appleVisionWithiPadDesign": "visionOS", "mac": "macOS"}


def say(msg):
    print(msg, flush=True)


def die(msg, code=1):
    sys.stderr.write(f"tuist: error: {msg}\n")
    sys.exit(code)


def data_root():
    return os.environ.get("OAD_TUIST_DIR") or os.path.join(
        os.environ.get("XDG_DATA_HOME") or os.path.expanduser("~/.local/share"), "omarchy-apple-dev/tuist")


def pd_dir():
    d = os.path.join(data_root(), "current")
    if not os.path.isfile(os.path.join(d, "lib/libProjectDescription.so")):
        die(f"Tuist's ProjectDescription is not installed: {FORK}/tuist/install.sh")
    return d


def xcodegen():
    return os.path.join(FORK, "xcodegen/bin/xcodegen")


# ---------------------------------------------------------------------------------------------- manifests


def root_of(path):
    """Tuist's root: the closest directory up with a Tuist/ directory, Tuist.swift or .git"""
    d = os.path.abspath(path)
    while True:
        if any(os.path.exists(os.path.join(d, m)) for m in ("Tuist", "Tuist.swift", ".git")):
            return d
        parent = os.path.dirname(d)
        if parent == d:
            return os.path.abspath(path)
        d = parent


def build_dir(path):
    d = os.path.join(path, "Derived/x86sim")
    os.makedirs(d, exist_ok=True)
    return d


def swiftc(args, cwd):
    r = subprocess.run(["swiftc", "-suppress-warnings"] + args, cwd=cwd, capture_output=True, text=True)
    if r.returncode != 0:
        sys.stderr.write(r.stdout + r.stderr)
        die("the manifest did not compile (above)")


def helpers(root, out):
    """Tuist/ProjectDescriptionHelpers as a module next to ProjectDescription, rebuilt when a helper changes"""
    srcs = sorted(glob.glob(os.path.join(root, "Tuist/ProjectDescriptionHelpers/**/*.swift"), recursive=True))
    if not srcs:
        return []
    pd = pd_dir()
    h = hashlib.sha256(b"".join(open(s, "rb").read() for s in srcs) + pd.encode()).hexdigest()[:16]
    d = os.path.join(out, "helpers-" + h)
    if not os.path.isfile(os.path.join(d, "libProjectDescriptionHelpers.so")):
        os.makedirs(d, exist_ok=True)
        swiftc(["-emit-library", "-emit-module", "-module-name", "ProjectDescriptionHelpers", "-parse-as-library",
                "-I", os.path.join(pd, "modules"), "-L", os.path.join(pd, "lib"), "-lProjectDescription",
                "-o", os.path.join(d, "libProjectDescriptionHelpers.so"), "-emit-module-path",
                os.path.join(d, "ProjectDescriptionHelpers.swiftmodule")] + srcs, cwd=d)
    return ["-I", d, "-L", d, "-lProjectDescriptionHelpers", "-Xlinker", "-rpath", "-Xlinker", d]


def dump(path, kind="project"):
    """The manifest (Project.swift / Workspace.swift / Package.swift in Tuist/) as Tuist's JSON, or None"""
    manifest = os.path.join(path, {"project": "Project.swift", "workspace": "Workspace.swift"}[kind])
    if not os.path.isfile(manifest):
        return None
    pd = pd_dir()
    out = build_dir(path)
    exe = os.path.join(out, kind + "-manifest")
    swiftc(["-I", os.path.join(pd, "modules"), "-L", os.path.join(pd, "lib"), "-lProjectDescription",
            "-Xlinker", "-rpath", "-Xlinker", os.path.join(pd, "lib")] + helpers(root_of(path), out) +
           [manifest, "-o", exe], cwd=path)
    r = subprocess.run([exe, "--tuist-dump"], cwd=path, capture_output=True, text=True)
    m = re.search(r"TUIST_MANIFEST_START\n(.*)\nTUIST_MANIFEST_END", r.stdout, re.S)
    if r.returncode != 0 or not m:
        sys.stderr.write(r.stdout + r.stderr)
        die(f"{manifest} did not run")
    return json.loads(m.group(1))


# ---------------------------------------------------------------------------------------------- values


def case(v):
    """Swift's synthesized Codable enum: {"case": payload} -> (case, payload)"""
    if isinstance(v, dict) and len(v) == 1:
        k = next(iter(v))
        return k, v[k]
    return v, None


def path_of(p, manifest_dir, root):
    if p is None:
        return None
    if isinstance(p, str):
        return os.path.join(manifest_dir, p)
    s = p.get("pathString", "")
    if os.path.isabs(s):
        return s
    base = root if p.get("type") == "relativeToRoot" else manifest_dir
    return os.path.normpath(os.path.join(base, s))


def setting_value(v):
    k, payload = case(v)
    if k in ("string", "array"):
        return payload.get("_0") if isinstance(payload, dict) else payload
    return v


def settings_dict(d):
    return {k: setting_value(v) for k, v in (d or {}).items()}


def plist_value(v):
    k, p = case(v)
    p = p.get("_0") if isinstance(p, dict) and "_0" in p else p
    if k == "array":
        return [plist_value(x) for x in p]
    if k == "dictionary":
        return {kk: plist_value(vv) for kk, vv in p.items()}
    return p


def version_str(v):
    if isinstance(v, str):
        return v
    s = f"{v.get('major', 0)}.{v.get('minor', 0)}.{v.get('patch', 0)}"
    if v.get("prereleaseIdentifiers"):
        s += "-" + ".".join(v["prereleaseIdentifiers"])
    return s


def requirement(req):
    k, p = case(req)
    if k == "upToNextMajor":
        return {"from": version_str(p["from"])}
    if k == "upToNextMinor":
        return {"minorVersion": version_str(p["from"])}
    if k == "exact":
        return {"exactVersion": version_str(p.get("_0", p.get("version", p)))}
    if k == "range":
        return {"minVersion": version_str(p["from"]), "maxVersion": version_str(p["to"])}
    if k == "branch":
        return {"branch": p.get("_0", p)}
    if k == "revision":
        return {"revision": p.get("_0", p)}
    die(f"unsupported package requirement {req}")


# ---------------------------------------------------------------------------------------------- globs


def collapse(p):
    """A file inside an opaque folder (asset catalog, .icon, bundle, ...) stands for that folder"""
    parts = p.split(os.sep)
    for i, part in enumerate(parts):
        if part.endswith(OPAQUE):
            return os.sep.join(parts[: i + 1])
    return p


def expand(pattern, excluding=()):
    hits = glob.glob(pattern, recursive=True) if any(c in pattern for c in "*?[") else (
        [pattern] if os.path.exists(pattern) else [])
    ex = set()
    for e in excluding:
        ex.update(os.path.normpath(x) for x in glob.glob(e, recursive=True))
    out = []
    for h in hits:
        h = os.path.normpath(h)
        c = collapse(h)
        if c != h and os.path.normpath(pattern) != c and not pattern.endswith(OPAQUE):
            h = c
        if os.path.isdir(h) and not h.endswith(OPAQUE):
            continue
        if h in ex or any(h.startswith(x + os.sep) for x in ex):
            continue
        if h not in out:
            out.append(h)
    return sorted(out)


# ---------------------------------------------------------------------------------------------- the spec


def default_info(t, project):
    """Tuist's default Info.plist content (TuistGenerator's InfoPlistContentProvider)"""
    product = CAMEL.get(t["product"], t["product"])
    if product in ("staticLibrary", "dynamicLibrary"):
        return None
    c = {"CFBundleDevelopmentRegion": "$(DEVELOPMENT_LANGUAGE)", "CFBundleIdentifier": "$(PRODUCT_BUNDLE_IDENTIFIER)",
         "CFBundleInfoDictionaryVersion": "6.0", "CFBundleName": "$(PRODUCT_NAME)", "CFBundleShortVersionString": "1.0",
         "CFBundleVersion": "1"}
    ptype = {"app": "APPL", "appClip": "APPL", "uiTests": "BNDL", "unitTests": "BNDL", "bundle": "BNDL",
             "framework": "FMWK", "staticFramework": "FMWK", "appExtension": "XPC!", "stickerPackExtension": "XPC!",
             "messagesExtension": "XPC!", "xpc": "XPC!", "extensionKitExtension": "XPC!", "systemExtension": "SYSX",
             "watch2App": "$(PRODUCT_BUNDLE_PACKAGE_TYPE)", "watch2Extension": "$(PRODUCT_BUNDLE_PACKAGE_TYPE)",
             "tvTopShelfExtension": "$(PRODUCT_BUNDLE_PACKAGE_TYPE)"}.get(product)
    if ptype:
        c["CFBundlePackageType"] = ptype
    plats = {PLATFORM_OF.get(d) for d in t["destinations"]}
    if product != "bundle" or plats == {"macOS"}:
        c["CFBundleExecutable"] = "$(EXECUTABLE_NAME)"
    if product == "app" and "iOS" in plats:
        c.update({"LSRequiresIPhoneOS": True, "UIRequiredDeviceCapabilities": ["armv7"],
                  "UISupportedInterfaceOrientations": ["UIInterfaceOrientationPortrait",
                                                       "UIInterfaceOrientationLandscapeLeft",
                                                       "UIInterfaceOrientationLandscapeRight"],
                  "UIApplicationSceneManifest": {"UIApplicationSupportsMultipleScenes": False,
                                                 "UISceneConfigurations": {}}})
        if "iPad" in t["destinations"]:
            c["UISupportedInterfaceOrientations~ipad"] = ["UIInterfaceOrientationPortrait",
                                                          "UIInterfaceOrientationPortraitUpsideDown",
                                                          "UIInterfaceOrientationLandscapeLeft",
                                                          "UIInterfaceOrientationLandscapeRight"]
    if product == "app" and "macOS" in plats:
        c.update({"CFBundleIconFile": "", "LSMinimumSystemVersion": "$(MACOSX_DEPLOYMENT_TARGET)",
                  "NSMainStoryboardFile": "Main", "NSPrincipalClass": "NSApplication"})
    if "macOS" in plats:
        c["NSHumanReadableCopyright"] = "Copyright ©. All rights reserved."
    host = next((h for h in project["targets"] if any(case(d)[0] == "target" and case(d)[1].get("name") == t["name"]
                                                       for d in h.get("dependencies", []))), None)
    if product == "watch2App":
        c.update({"CFBundleDisplayName": t["name"], "WKWatchKitApp": True,
                  "UISupportedInterfaceOrientations": ["UIInterfaceOrientationPortrait",
                                                       "UIInterfaceOrientationPortraitUpsideDown"]})
        if host:
            c["WKCompanionAppBundleIdentifier"] = host["bundleId"]
    if product == "watch2Extension":
        c.update({"CFBundleDisplayName": t["name"], "WKExtensionDelegateClassName": "$(PRODUCT_MODULE_NAME).ExtensionDelegate",
                  "NSExtension": {"NSExtensionAttributes": {"WKAppBundleIdentifier": host["bundleId"]} if host else {},
                                  "NSExtensionPointIdentifier": "com.apple.watchkit"}})
    return c


def package_products(packages, out):
    """product name -> package name, from the packages' own manifests (resolved once, cached by their list)"""
    remote = {n: p for n, p in packages.items() if "url" in p}
    local = {n: p for n, p in packages.items() if "path" in p}
    key = hashlib.sha256(json.dumps(packages, sort_keys=True).encode()).hexdigest()[:16]
    cache = os.path.join(out, f"products-{key}.json")
    if os.path.isfile(cache):
        return json.load(open(cache))
    found = {}
    dirs = {n: p["path"] for n, p in local.items()}
    if remote:
        say("== tuist: resolving the Swift packages to find their products")
        d = os.path.join(out, "packages")
        os.makedirs(d, exist_ok=True)
        deps = []
        for n, p in remote.items():
            r = ("from: \"%s\"" % p["from"]) if "from" in p else (".upToNextMinor(from: \"%s\")" % p["minorVersion"]) \
                if "minorVersion" in p else ("exact: \"%s\"" % p["exactVersion"]) if "exactVersion" in p else \
                ("\"%s\"..<\"%s\"" % (p["minVersion"], p["maxVersion"])) if "minVersion" in p else \
                ("branch: \"%s\"" % p["branch"]) if "branch" in p else ("revision: \"%s\"" % p["revision"])
            deps.append(f'        .package(url: "{p["url"]}", {r}),')
        with open(os.path.join(d, "Package.swift"), "w") as f:
            f.write("// swift-tools-version: 5.9\nimport PackageDescription\nlet package = Package(name: \"Deps\", "
                    "dependencies: [\n" + "\n".join(deps) + "\n])\n")
        r = subprocess.run(["swift", "package", "resolve"], cwd=d, capture_output=True, text=True)
        if r.returncode != 0:
            sys.stderr.write(r.stderr)
            die("could not resolve the project's Swift packages")
        state = json.load(open(os.path.join(d, ".build/workspace-state.json")))
        for dep in state["object"]["dependencies"]:
            url = dep["packageRef"].get("location", "").rstrip("/")
            name = next((n for n, p in remote.items() if p["url"].rstrip("/").removesuffix(".git") ==
                         url.removesuffix(".git")), None)
            if name:
                dirs[name] = os.path.join(d, ".build/checkouts", dep["subpath"])
    for name, path in dirs.items():
        r = subprocess.run(["swift", "package", "dump-package", "--package-path", path], capture_output=True, text=True)
        if r.returncode == 0:
            for prod in json.loads(r.stdout).get("products", []):
                found.setdefault(prod["name"], name)
    json.dump(found, open(cache, "w"))
    return found


def package_name(url):
    return re.sub(r"\.git$", "", url.rstrip("/").split("/")[-1])


def spec(project, path, root):
    """Tuist's project JSON as an XcodeGen spec"""
    name = project["name"]
    out = build_dir(path)
    s = {"name": name, "options": {"createIntermediateGroups": True, "groupSortPosition": "top",
                                   "transitivelyLinkDependencies": False}, "settings": {}, "targets": {}}
    if project.get("organizationName"):
        s["attributes"] = {"ORGANIZATIONNAME": project["organizationName"]}
    pset = project.get("settings") or {}
    configs = pset.get("configurations") or [{"name": {"rawValue": "Debug"}, "variant": "debug"},
                                             {"name": {"rawValue": "Release"}, "variant": "release"}]
    s["configs"] = {c["name"]["rawValue"]: c["variant"] for c in configs}
    s["settings"] = {"base": settings_dict(pset.get("base")),
                     "configs": {c["name"]["rawValue"]: settings_dict(c.get("settings")) for c in configs if c.get("settings")}}
    for c in configs:
        if c.get("xcconfig"):
            s.setdefault("configFiles", {})[c["name"]["rawValue"]] = path_of(c["xcconfig"], path, root)
    ds = case(pset.get("defaultSettings") or {"recommended": {}})[0]
    if ds == "none":
        s["options"]["settingPresets"] = "none"
    elif ds == "essential":
        s["options"]["settingPresets"] = "project"
    # Swift packages: the project's, then Tuist/Package.swift's (external dependencies)
    packages = {}
    for p in (project.get("packages") or []) + (project.get("packageDependencies") or []):
        if "kind" in p:  # Package.Dependency (Tuist 4's packages: [.package(url:...)])
            k, v = case(p["kind"])
            if k == "sourceControl":
                rk, rv = case(v["requirement"])
                rv = rv.get("_0", rv) if isinstance(rv, dict) else rv
                req = {"range": lambda: {"minVersion": version_str(rv[0]), "maxVersion": version_str(rv[1])},
                       "exact": lambda: {"exactVersion": version_str(rv)}, "branch": lambda: {"branch": rv},
                       "revision": lambda: {"revision": rv}}.get(rk)
                if not req:
                    die(f"unsupported package requirement {v['requirement']}")
                loc = v["location"] if isinstance(v["location"], str) else v["location"].get("remote", [{}])[0].get("urlString", "")
                packages[package_name(loc)] = {"url": loc, **req()}
                continue
            if k == "fileSystem":
                lp = path_of(v.get("path"), path, root)
                packages[os.path.basename(lp)] = {"path": lp}
                continue
            die(f"unsupported package {p}")
        k, v = case(p)
        if k == "remote":
            packages[package_name(v["url"])] = {"url": v["url"], **requirement(v["requirement"])}
        elif k == "local":
            lp = path_of(v.get("path"), path, root)
            packages[os.path.basename(lp)] = {"path": lp}
        else:
            die(f"unsupported package {p}")
    tuist_pkg = os.path.join(root, "Tuist/Package.swift")
    if os.path.isfile(tuist_pkg):
        r = subprocess.run(["swift", "package", "dump-package", "--package-path", os.path.dirname(tuist_pkg)],
                           capture_output=True, text=True)
        if r.returncode == 0:
            for dep in json.loads(r.stdout).get("dependencies", []):
                k, v = case(dep)
                v = v[0] if isinstance(v, list) else v
                if k == "sourceControl":
                    url = v["location"]["remote"][0]["urlString"] if "remote" in v["location"] else v["location"]
                    kind, req = case(v["requirement"])
                    req = req[0] if isinstance(req, list) else req
                    r2 = {"range": {"minVersion": req.get("lowerBound"), "maxVersion": req.get("upperBound")} if isinstance(req, dict) else {},
                          "exact": {"exactVersion": req}, "branch": {"branch": req}, "revision": {"revision": req}}.get(kind, {})
                    packages[package_name(url)] = {"url": url, **r2}
                elif k == "fileSystem":
                    packages[os.path.basename(v["path"])] = {"path": v["path"]}
    if packages:
        s["packages"] = packages
    products = package_products(packages, out) if packages else {}

    for t in project["targets"]:
        product = CAMEL.get(t["product"], t["product"])
        plats = [PLATFORM_OF[d] for d in t["destinations"] if d in PLATFORM_OF]
        platform = plats[0] if plats else "iOS"
        x = {"type": PRODUCT_TYPES.get(product) or die(f"{t['name']}: unsupported product {t['product']}"),
             "platform": platform, "sources": [], "dependencies": [], "settings": {"base": {}, "configs": {}}}
        if product == "app" and platform == "watchOS":
            x["type"] = "application"
        dt = (t.get("deploymentTargets") or {}).get(platform)
        if dt:
            x["deploymentTarget"] = dt
        base = x["settings"]["base"]
        base["PRODUCT_BUNDLE_IDENTIFIER"] = t["bundleId"]
        if t.get("productName"):
            base["PRODUCT_NAME"] = t["productName"]
        if platform == "iOS":
            fam = [f for d, f in (("iPhone", "1"), ("iPad", "2")) if d in t["destinations"]]
            base["TARGETED_DEVICE_FAMILY"] = ",".join(fam) or "1"
            if "macWithiPadDesign" not in t["destinations"]:
                base["SUPPORTS_MAC_DESIGNED_FOR_IPHONE_IPAD"] = "NO"
        # Info.plist: a file, or Tuist's default extended with the manifest's keys (written to Derived/InfoPlists)
        ik, ip = case(t.get("infoPlist") or {"default": {}})
        if ik == "file":
            base["INFOPLIST_FILE"] = os.path.relpath(path_of(ip["path"], path, root), path)
        elif ik in ("default", "extendingDefault", "dictionary"):
            content = {} if ik == "dictionary" else (default_info(t, project) or {})
            extra = (ip or {}).get("with") if ik == "extendingDefault" else (ip or {}).get("_0") if ik == "dictionary" else None
            content.update({k: plist_value(v) for k, v in (extra or {}).items()})
            x["info"] = {"path": f"Derived/InfoPlists/{t['name']}-Info.plist", "properties": content}
        ek, ep = case(t.get("entitlements")) if t.get("entitlements") else (None, None)
        if ek == "file":
            base["CODE_SIGN_ENTITLEMENTS"] = os.path.relpath(path_of(ep["path"], path, root), path)
        elif ek == "dictionary":
            x["entitlements"] = {"path": f"Derived/Entitlements/{t['name']}.entitlements",
                                 "properties": {k: plist_value(v) for k, v in ep.get("_0", {}).items()}}
        tset = t.get("settings") or {}
        base.update(settings_dict(tset.get("base")))
        for c in tset.get("configurations") or []:
            if c.get("settings"):
                x["settings"]["configs"][c["name"]["rawValue"]] = settings_dict(c["settings"])
            if c.get("xcconfig"):
                x.setdefault("configFiles", {})[c["name"]["rawValue"]] = path_of(c["xcconfig"], path, root)
        # a literal PRODUCT_NAME names the product (and the reference other targets embed)
        pn = t.get("productName") or base.get("PRODUCT_NAME")
        if isinstance(pn, str) and "$" not in pn and pn != t["name"]:
            x["productName"] = pn
        # sources and resources, globbed as Tuist globs them
        seen = set()
        for g in (t.get("sources") or {}).get("globs", []):
            pat = path_of(g["glob"], path, root)
            for f in expand(pat, [path_of(e, path, root) for e in g.get("excluding", [])]):
                if f not in seen:
                    seen.add(f)
                    entry = {"path": os.path.relpath(f, path), "buildPhase": "sources"}
                    if g.get("compilerFlags"):
                        entry["compilerFlags"] = g["compilerFlags"]
                    x["sources"].append(entry)
        for r in (t.get("resources") or {}).get("resources", []):
            k, v = case(r)
            if k == "glob":
                files = expand(path_of(v["pattern"], path, root), [path_of(e, path, root) for e in v.get("excluding", [])])
            elif k == "folderReference":
                files = [path_of(v["path"], path, root)]
            else:
                die(f"{t['name']}: unsupported resource {r}")
            for f in files:
                if f in seen:
                    continue
                seen.add(f)
                entry = {"path": os.path.relpath(f, path), "buildPhase": "resources"}
                if k == "folderReference":
                    entry["type"] = "folder"
                x["sources"].append(entry)
        for k in ("headers",):
            if t.get(k):
                sys.stderr.write(f"tuist: warning: {t['name']}: {k} are not carried over\n")
        # dependencies
        for d in t.get("dependencies", []):
            k, v = case(d)
            optional = isinstance(v, dict) and v.get("status") == "optional"
            if k == "target":
                x["dependencies"].append({"target": v["name"]})
            elif k in ("package", "external"):
                prod = v.get("product") or v.get("name")
                pkg = products.get(prod) or next((n for n in packages if n.lower() == prod.lower()), None)
                if not pkg:
                    die(f"{t['name']}: no Swift package of the project has a product {prod}")
                x["dependencies"].append({"package": pkg, "product": prod})
            elif k in ("framework", "xcframework"):
                x["dependencies"].append({"framework": os.path.relpath(path_of(v["path"], path, root), path),
                                          **({"weak": True} if optional else {})})
            elif k == "library":
                x["dependencies"].append({"framework": os.path.relpath(path_of(v["path"], path, root), path),
                                          "embed": False})
            elif k == "sdk":
                n = v["name"]
                kind = case(v.get("type", "framework"))[0]
                x["dependencies"].append({"sdk": f"{n}.framework" if kind == "framework" else f"lib{n}.tbd",
                                          **({"weak": True} if optional else {})})
            elif k == "xctest":
                x["dependencies"].append({"sdk": "XCTest.framework"})
            elif k == "project":
                die(f"{t['name']}: dependencies on other projects' targets are not supported here yet")
            else:
                die(f"{t['name']}: unsupported dependency {d}")
        # scripts
        for sc in t.get("scripts", []):
            sk, sv = case(sc["script"])
            if sk == "embedded":
                body = sv.get("_0", sv) if isinstance(sv, dict) else sv
            elif sk in ("scriptPath", "tool"):
                body = " ".join([sv.get("path", {}).get("pathString", "") if sk == "scriptPath" else sv.get("path", "")]
                                + sv.get("args", []))
            else:
                body = str(sv)
            e = {"name": sc.get("name", "Script"), "script": body, "basedOnDependencyAnalysis": sc.get("basedOnDependencyAnalysis", True)}
            for a, b in (("inputPaths", "inputFiles"), ("outputPaths", "outputFiles")):
                if sc.get(a):
                    e[b] = sc[a]
            x["preBuildScripts" if sc.get("order") == "pre" else "postBuildScripts"] = \
                x.get("preBuildScripts" if sc.get("order") == "pre" else "postBuildScripts", []) + [e]
        s["targets"][t["name"]] = x

    # schemes: the manifest's, and Tuist's automatic ones unless disabled
    schemes = {}
    for sch in project.get("schemes") or []:
        e = {"build": {"targets": {r["targetName"]: "all" for r in (sch.get("buildAction") or {}).get("targets", [])}}}
        ta = sch.get("testAction") or {}
        if ta.get("targets"):
            e["test"] = {"config": ta.get("configuration", {}).get("rawValue", "Debug"),
                         "targets": [tt["target"]["targetName"] for tt in ta["targets"]],
                         "gatherCoverageData": bool((ta.get("options") or {}).get("coverage"))}
        ra = sch.get("runAction") or {}
        if ra:
            e["run"] = {"config": ra.get("configuration", {}).get("rawValue", "Debug")}
            ek_, ev_ = case(ra.get("executable") or {})
            if ek_ == "executable":
                e["run"]["executable"] = ev_["_0"]["targetName"]
        for act, key in (("archiveAction", "archive"), ("profileAction", "profile"), ("analyzeAction", "analyze")):
            if sch.get(act):
                e[key] = {"config": sch[act].get("configuration", {}).get("rawValue", "Release")}
        schemes[sch["name"]] = e
    auto = case((project.get("options") or {}).get("automaticSchemesOptions") or {"enabled": {}})[0]
    if auto != "disabled":
        for tn, x in s["targets"].items():
            if tn in schemes or x["type"].startswith("bundle.") and "test" in x["type"]:
                continue
            tests = [n for n, y in s["targets"].items() if y["type"] in ("bundle.unit-test", "bundle.ui-testing")
                     and any(d.get("target") == tn for d in y["dependencies"])]
            schemes[tn] = {"build": {"targets": {tn: "all"}}, "run": {"config": "Debug"},
                           **({"test": {"config": "Debug", "targets": tests}} if tests else {})}
    if schemes:
        s["schemes"] = schemes
    return s


def write_workspace(path, name, projects):
    ws = os.path.join(path, name + ".xcworkspace")
    os.makedirs(ws, exist_ok=True)
    refs = "".join(f'   <FileRef\n      location = "group:{p}">\n   </FileRef>\n' for p in projects)
    with open(os.path.join(ws, "contents.xcworkspacedata"), "w") as f:
        f.write(f'<?xml version="1.0" encoding="UTF-8"?>\n<Workspace\n   version = "1.0">\n{refs}</Workspace>\n')
    return ws


def generate(path):
    path = os.path.abspath(path)
    root = root_of(path)
    say("== tuist: loading the manifests")
    project = dump(path, "project")
    workspace = dump(path, "workspace")
    if not project:
        die(f"no Project.swift in {path}")
    if workspace and [p for p in workspace.get("projects", []) if os.path.normpath(path_of(p, path, root)) != path]:
        die("a workspace with several projects is not supported here yet")
    s = spec(project, path, root)
    out = build_dir(path)
    specfile = os.path.join(out, project["name"] + ".xcodegen.json")
    with open(specfile, "w") as f:
        json.dump(s, f, indent=2)
    say(f"== tuist: generating {project['name']}.xcodeproj")
    r = subprocess.run([xcodegen(), "generate", "--spec", specfile, "--project", path, "--project-root", path])
    if r.returncode != 0:
        die("XcodeGen could not write the project")
    # file types Tuist gives that XcodeGen does not know: Icon Composer icons go to actool as in Xcode
    pbx = os.path.join(path, project["name"] + ".xcodeproj/project.pbxproj")
    text = open(pbx, encoding="utf-8").read()
    fixed = text.replace("lastKnownFileType = wrapper.icon;", "lastKnownFileType = folder.iconcomposer.icon;")
    if fixed != text:
        open(pbx, "w", encoding="utf-8").write(fixed)
    ws = write_workspace(path, (workspace or {}).get("name") or project["name"], [project["name"] + ".xcodeproj"])
    say(f"Project generated: {ws}")
    return 0


def main(argv):
    if not argv or argv[0] in ("-h", "--help", "help"):
        print(__doc__)
        return 0
    cmd, rest = argv[0], argv[1:]
    path = "."
    if "--path" in rest:
        path = rest[rest.index("--path") + 1]
    elif "-p" in rest:
        path = rest[rest.index("-p") + 1]
    if cmd == "version":
        tv = open(os.path.join(data_root(), "current/version")).read().strip() if os.path.exists(
            os.path.join(data_root(), "current/version")) else "?"
        print(f"{tv} (Linux: ProjectDescription {tv} with XcodeGen)")
        return 0
    if cmd == "generate":
        return generate(path)
    if cmd in ("install", "fetch"):
        say("tuist: nothing to install here: Swift Build resolves the Swift packages when it builds")
        return 0
    if cmd == "dump":
        kind = rest[0] if rest and not rest[0].startswith("-") else "project"
        print(json.dumps(dump(os.path.abspath(path), kind), indent=2))
        return 0
    die(f"`tuist {cmd}` is not available on Linux (generate, install, dump, version)", 64)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
